USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS PSET2_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS CERVECERIA_DB;
CREATE SCHEMA IF NOT EXISTS CERVECERIA_DB.RAW;
CREATE SCHEMA IF NOT EXISTS CERVECERIA_DB.BRONZE;
CREATE SCHEMA IF NOT EXISTS CERVECERIA_DB.SILVER;
CREATE SCHEMA IF NOT EXISTS CERVECERIA_DB.GOLD;
CREATE SCHEMA IF NOT EXISTS CERVECERIA_DB.OBT;

CREATE ROLE IF NOT EXISTS PSET2_ROLE;
GRANT USAGE ON WAREHOUSE PSET2_WH TO ROLE PSET2_ROLE;
GRANT ALL ON DATABASE CERVECERIA_DB TO ROLE PSET2_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE CERVECERIA_DB TO ROLE PSET2_ROLE;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE CERVECERIA_DB TO ROLE PSET2_ROLE;
GRANT ALL ON FUTURE TABLES IN DATABASE CERVECERIA_DB TO ROLE PSET2_ROLE;
GRANT ALL ON FUTURE VIEWS IN DATABASE CERVECERIA_DB TO ROLE PSET2_ROLE;

CREATE USER IF NOT EXISTS PSET2_USER
  TYPE = SERVICE
  DEFAULT_ROLE = PSET2_ROLE
  DEFAULT_WAREHOUSE = PSET2_WH
  RSA_PUBLIC_KEY = 'PEGA_AQUI_TU_LLAVE_PUBLICA';
GRANT ROLE PSET2_ROLE TO USER PSET2_USER;

-- También le damos el rol a tu usuario, para que puedas ver las tablas que cree el pipeline
GRANT ROLE PSET2_ROLE TO USER <YOUR_USER_NAME>;

SHOW SCHEMAS IN DATABASE CERVECERIA_DB;

DESC USER PSET2_USER;
